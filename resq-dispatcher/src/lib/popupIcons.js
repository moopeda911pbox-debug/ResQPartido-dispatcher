// Which header icon + tint a report gets, from its incident type. The citizen
// app's SOS types are Fire, Flood, Typhoon, Earthquake, Landslide, Vehicular
// Accident, Medical Emergency and Crime in Progress (see lib/alertTypes.js).
export function incidentIcon(type) {
  const t = String(type || "").toLowerCase();
  if (/fire|sunog/.test(t)) return { icon: "flame", tone: "fire" };
  if (/flood|baha/.test(t)) return { icon: "droplets", tone: "water" };
  if (/typhoon|storm|bagyo/.test(t)) return { icon: "wind", tone: "water" };
  if (/earthquake|lindol/.test(t)) return { icon: "activity", tone: "ground" };
  if (/landslide|guho/.test(t)) return { icon: "mountain", tone: "ground" };
  if (/accident|crash|collision|vehic/.test(t)) return { icon: "car", tone: "accident" };
  if (/medic|health|injur|ambulance/.test(t)) return { icon: "heart-pulse", tone: "medical" };
  if (/crime|theft|robber|assault|violence|police|shoot/.test(t)) return { icon: "shield-alert", tone: "crime" };
  return { icon: "triangle-alert", tone: "default" };
}
